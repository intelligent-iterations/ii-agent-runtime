import assert from 'node:assert/strict';
import { test } from 'node:test';
import { mkdtempSync, readFileSync, renameSync, rmSync, symlinkSync, writeFileSync, realpathSync, linkSync, readdirSync } from 'node:fs';
import { randomUUID } from 'node:crypto';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { loadExecutionInputsArtifact, saveExecutionInputsArtifact } from '../../src/runtime/execution-artifacts.js';
import { compileExecutionInputs } from '../../src/runtime/execution-inputs.js';
import { inputs } from '../execution-input-fixture.js';

test('retained execution inputs require independently trusted identity and reject damaged or redirected files', t => {
  const root = realpathSync(mkdtempSync(join(tmpdir(), 'execution-input-test-')));
  const owner = randomUUID(); writeFileSync(join(root, '.test-owner'), owner, { flag: 'wx' });
  t.after(() => { assert.equal(readFileSync(join(root, '.test-owner'), 'utf8'), owner); rmSync(root, { recursive: true }); });
  const input = inputs(), compiled = compileExecutionInputs(input);
  const before = readdirSync(root);
  assert.throws(() => saveExecutionInputsArtifact(root, input, { secretValues: ['Implement the approved change.'] }));
  assert.deepEqual(readdirSync(root), before, 'secret rejection happens before filesystem effects');
  const directory = saveExecutionInputsArtifact(root, input);
  const another = saveExecutionInputsArtifact(root, input);
  assert.notEqual(another, directory);
  assert.deepEqual(loadExecutionInputsArtifact(another, compiled.artifactDigest, 1048576), compiled);
  const load = () => loadExecutionInputsArtifact(directory, compiled.artifactDigest, 1048576);
  assert.deepEqual(load(), compiled);
  assert.throws(() => loadExecutionInputsArtifact(directory, compiled.artifactDigest, 5));
  assert.throws(() => loadExecutionInputsArtifact(directory, `sha256:${'0'.repeat(64)}`, 1048576));
  const canonical = join(directory, 'canonical.json');
  writeFileSync(canonical, compiled.canonical + ' ');
  assert.throws(load, /INTEGRITY/);
  writeFileSync(canonical, compiled.canonical);
  const manifestFile = join(directory, 'manifest.json');
  const originalManifest = readFileSync(manifestFile, 'utf8');
  const manifest = JSON.parse(originalManifest); manifest.inputDigest = `sha256:${'0'.repeat(64)}`;
  writeFileSync(manifestFile, JSON.stringify(manifest));
  assert.throws(load, /IDENTITY/);
  writeFileSync(manifestFile, originalManifest);
  const saved = join(directory, 'saved.json'); renameSync(canonical, saved);
  assert.throws(load);
  symlinkSync(saved, canonical);
  assert.throws(load);
  assert.equal(readFileSync(join(root, '.test-owner'), 'utf8'), owner);
  rmSync(canonical); linkSync(saved, canonical);
  assert.throws(load, /Invalid artifact/);
});
